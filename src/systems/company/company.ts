import { links, priceMult, sellable, type Run } from '../run/run';
import { marketTotals, type MarketContext, type MarketTotals } from './market';

/** The same shipped product drives the simulation, forecasts and customer panels. */
export function companyContext(run: Run): MarketContext {
  return {
    levels: Object.fromEntries(run.blocks.filter((b) => b.live).map((b) => [b.kind, b.level])),
    links: links(run),
    stage: run.stage,
    infrastructure: run.infrastructure,
    support: run.strategy.support,
    processing: run.strategy.processing,
    cardStacks: { ...run.cardStacks },
    debt: run.debt,
    down: run.down,
    sellable: sellable(run),
    payments: run.live.has('pay'),
    basePrice: run.idea.aud.pay,
    priceMult: priceMult(run),
    segmentPrice: {
      small: run.eff.small_pay,
      medium: run.eff.small_pay,
      large: run.eff.corp_pay,
    },
    tokenMult: run.idea.tech.tokens * run.eff.tokens * run.mod.tokens,
    // Promotion and specialization already changed the number of leads generated by work.
    promotionMult: 1,
    referralMult: run.eff.word_of_mouth * run.idea.form.viral,
  };
}

export function companyTotals(run: Run): MarketTotals {
  return marketTotals(run.market, companyContext(run));
}

/** Named contracts are separate customers, never additional copies of a cohort. */
export function customerCount(run: Run): number {
  return run.clients.length + companyTotals(run).count;
}
